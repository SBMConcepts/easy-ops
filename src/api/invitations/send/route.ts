import { Auth0Client } from '@auth0/nextjs-auth0/server'
import { createClient } from '@supabase/supabase-js'
import { NextRequest, NextResponse } from 'next/server'

// Roles an admin may hand out via an invitation. `owner` is reserved for the
// workspace creator during provisioning and is intentionally excluded.
const ASSIGNABLE_ROLES = ['admin', 'manager', 'supervisor', 'employee'] as const
type AssignableRole = (typeof ASSIGNABLE_ROLES)[number]

export async function POST(req: NextRequest) {
  const auth0 = new Auth0Client()
  const session = await auth0.getSession()
  if (!session?.user) {
    return NextResponse.json({ error: 'Unauthenticated' }, { status: 401 })
  }

  const orgId = session.user.org_id as string | undefined
  if (!orgId) {
    return NextResponse.json({ error: 'No active organization.' }, { status: 403 })
  }

  const { email, role } = (await req.json()) as { email?: string; role?: string }
  const normalizedEmail = email?.toLowerCase().trim()
  if (!normalizedEmail || !role || !ASSIGNABLE_ROLES.includes(role as AssignableRole)) {
    return NextResponse.json({ error: 'A valid email and role are required.' }, { status: 400 })
  }

  // RLS-scoped client: forwarding the caller's Auth0 access token makes Postgres
  // evaluate every query as this user, so the membership check below can only
  // ever read the caller's own row in this org.
  const { token: accessToken } = await auth0.getAccessToken()
  const supabase = createClient(process.env.SUPABASE_URL!, process.env.SUPABASE_ANON_KEY!, {
    global: { headers: { Authorization: `Bearer ${accessToken}` } },
  })

  // Confirm the caller is an owner/admin in this org before inviting anyone.
  const { data: caller } = await supabase
    .from('org_members')
    .select('role')
    .eq('org_id', orgId)
    .single()

  if (!caller || !['owner', 'admin'].includes(caller.role)) {
    return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
  }

  // Insert the invitation (token + expiry are generated by DB defaults).
  const { data: invite, error } = await supabase
    .from('invitations')
    .insert({ org_id: orgId, email: normalizedEmail, role })
    .select('token, expires_at')
    .single()

  if (error || !invite) {
    return NextResponse.json(
      { error: error?.message ?? 'Failed to create invitation.' },
      { status: 500 }
    )
  }

  // TODO: send email with the invite link:
  //   `${process.env.APP_BASE_URL}/accept-invite?token=${invite.token}`

  return NextResponse.json({ ok: true, token: invite.token, expiresAt: invite.expires_at })
}
